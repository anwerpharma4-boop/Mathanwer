extension L10nContext on BuildContext {
  L10n get l10n => L10n(AppScope.of(this).settings.languageCode);
  String tr(String key) => l10n.t(key);
}

/// Wraps English learning content so it is always laid out LTR, even when
/// the interface language is Arabic.
class EnglishContent extends StatelessWidget {
  const EnglishContent({super.key, required this.child});

  final Widget child;

  @override
  Widget build(BuildContext context) =>
      Directionality(textDirection: TextDirection.ltr, child: child);
}
